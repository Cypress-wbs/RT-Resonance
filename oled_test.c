static void oled_delay(void) { for(volatile int i = 0; i < 5; i++); }
static void oled_i2c_start(void) { SDA_H(); SCL_H(); oled_delay(); SDA_L(); oled_delay(); SCL_L(); oled_delay(); }
static void oled_i2c_stop(void) { SDA_L(); SCL_H(); oled_delay(); SDA_H(); oled_delay(); }
static void oled_i2c_write_byte(rt_uint8_t data) {
    for (int i = 0; i < 8; i++) {
        if (data & 0x80) SDA_H(); else SDA_L();
        oled_delay(); SCL_H(); oled_delay(); SCL_L(); oled_delay();
        data <<= 1;
    }
    SDA_H(); oled_delay(); SCL_H(); oled_delay(); SCL_L(); oled_delay();
}

void oled_write_cmd(rt_uint8_t cmd) { oled_i2c_start(); oled_i2c_write_byte(0x78); oled_i2c_write_byte(0x00); oled_i2c_write_byte(cmd); oled_i2c_stop(); }
void oled_write_data(rt_uint8_t data) { oled_i2c_start(); oled_i2c_write_byte(0x78); oled_i2c_write_byte(0x40); oled_i2c_write_byte(data); oled_i2c_stop(); }

void oled_set_pos(rt_uint8_t x, rt_uint8_t page) {
    oled_write_cmd(0xb0 + page);
    oled_write_cmd(((x & 0xf0) >> 4) | 0x10);
    oled_write_cmd((x & 0x0f) | 0x01);
}

void oled_clear(void) {
    for (rt_uint8_t i = 0; i < 8; i++) {
        oled_set_pos(0, i);
        for (rt_uint8_t j = 0; j < 128; j++) oled_write_data(0x00);
    }
}

void oled_init(void) {
    rt_pin_mode(OLED_SCL_PIN, PIN_MODE_OUTPUT_OD);
    rt_pin_mode(OLED_SDA_PIN, PIN_MODE_OUTPUT_OD);
    rt_thread_mdelay(100);
    oled_write_cmd(0xAE); oled_write_cmd(0x00); oled_write_cmd(0x10);
    oled_write_cmd(0x40); oled_write_cmd(0x81); oled_write_cmd(0xCF);
    oled_write_cmd(0xA1); oled_write_cmd(0xC8); oled_write_cmd(0xA6);
    oled_write_cmd(0xA8); oled_write_cmd(0x3F); oled_write_cmd(0xD3);
    oled_write_cmd(0x00); oled_write_cmd(0xD5); oled_write_cmd(0x80);
    oled_write_cmd(0xD9); oled_write_cmd(0xF1); oled_write_cmd(0xDA);
    oled_write_cmd(0x12); oled_write_cmd(0xDB); oled_write_cmd(0x40);
    oled_write_cmd(0x8D); oled_write_cmd(0x14); oled_write_cmd(0xAF);
    oled_clear();
}

void oled_show_char(rt_uint8_t x, rt_uint8_t page, char chr) {
    rt_uint8_t c = chr - ' ';
    oled_set_pos(x, page);
    for (rt_uint8_t i = 0; i < 6; i++) oled_write_data(F6x8[c][i]);
}

void oled_show_string(rt_uint8_t x, rt_uint8_t page, char *str) {
    while (*str) {
        oled_show_char(x, page, *str);
        x += 6; str++;
    }
}

